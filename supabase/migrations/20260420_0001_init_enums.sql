-- ============================================================================
-- FinAgent OS — Migration 0001: Enum Types
-- ============================================================================
-- Establishes the controlled vocabularies referenced by every table in the
-- FinAgent OS schema. Enums are created first because they are structural
-- dependencies for process_owners, agent_registry, shadow_ledger, hitl_queue,
-- and materiality_thresholds.
--
-- Control IDs referenced:
--   FAO-GOV-003  Risk-Tier Classification (risk_tier enum)
--   FAO-GOV-009  Policy Outcome vocabulary (policy_outcome enum)
--   FAO-GOV-004  HITL Gateway (hitl_status, hitl_decision enums)
--
-- Author: Rizwan Ahmed, ACCA · Velocyt Consulting
-- Date:   2026-04-20
-- ============================================================================

-- Risk tier for agents and process owners. BLOCKED is never assigned as an
-- agent's operating tier — it appears only as a policy outcome. The enum
-- includes it here for type consistency across risk vocabulary.
CREATE TYPE risk_tier AS ENUM (
  'GREEN',
  'AMBER',
  'RED',
  'BLOCKED'
);

-- Agent lifecycle status. STUB_DOCUMENTED captures the three stub modules
-- (Close Orchestrator, Variance Analyzer, Treasury Monitor) that are designed
-- but not yet implemented. They inherit governance controls but cannot execute.
CREATE TYPE agent_status AS ENUM (
  'ACTIVE',
  'STUB_DOCUMENTED',
  'DEPRECATED'
);

-- Policy outcomes — the named vocabulary every agent execution produces.
-- Exactly one outcome per execution. These are computed deterministically
-- by the policy engine, never generated by an LLM. FAO-GOV-009.
CREATE TYPE policy_outcome AS ENUM (
  'ALLOW',
  'ALLOW_WITH_OBLIGATIONS',
  'REQUIRE_HUMAN',
  'DENY',
  'BLOCKED'
);

-- Sub-tier granularity within REQUIRE_HUMAN, used to route to the correct
-- HITL approval threshold (single-approver vs dual-approver).
CREATE TYPE policy_sub_tier AS ENUM (
  'STANDARD',
  'CRITICAL'
);

-- HITL request lifecycle. Populated on every REQUIRE_HUMAN outcome; the
-- default NOT_REQUIRED appears on shadow_ledger entries that did not
-- route through the HITL gate.
CREATE TYPE hitl_status AS ENUM (
  'NOT_REQUIRED',
  'PENDING',
  'APPROVED',
  'REJECTED'
);

-- Terminal decision states for hitl_queue rows.
CREATE TYPE hitl_decision AS ENUM (
  'PENDING',
  'APPROVED',
  'REJECTED'
);

-- Execution status recorded in shadow_ledger. PARTIAL covers runs that
-- completed some assets but failed others. ROLLED_BACK covers runs the
-- Rollback Engine (FAO-GOV-005) has reverted.
CREATE TYPE execution_status AS ENUM (
  'SUCCESS',
  'FAILURE',
  'PARTIAL',
  'ROLLED_BACK'
);

-- Asset class for materiality thresholds. Stablecoins get tight ratio
-- bands (1.00-1.005); majors and mid-caps get wider bands reflecting
-- Kraken's published over-reservation posture (BTC historically ~1.15).
CREATE TYPE asset_class AS ENUM (
  'Stablecoin',
  'Major',
  'Mid_cap'
);

-- Attestation scope granularity. Mirrors Kraken's own Dec 2025 Proof of
-- Reserves scope split where Futures became a separately-attested record
-- rather than being merged into Spot.
CREATE TYPE attestation_scope AS ENUM (
  'Spot',
  'Futures',
  'Spot_and_Futures'
);
